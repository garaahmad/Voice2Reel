VERSION = "presenter-1"
PROFILES = {"fast": (540, 24, "ultrafast"), "quality": (720, 30, "veryfast")}
INK, RED = "#131719", "#c53b30"


def curve(points, steps=20):
    a, b, c, d = points
    return [
        (
            (1 - u) ** 3 * a[0] + 3 * (1 - u) ** 2 * u * b[0] + 3 * (1 - u) * u * u * c[0] + u**3 * d[0],
            (1 - u) ** 3 * a[1] + 3 * (1 - u) ** 2 * u * b[1] + 3 * (1 - u) * u * u * c[1] + u**3 * d[1],
        )
        for u in np.linspace(0, 1, steps)
    ]


def rounded_line(draw, points, width, color=INK):
    draw.line(points, fill=color, width=width, joint="curve")
    r = width / 2
    for x, y in (points[0], points[-1]):
        draw.ellipse((x - r, y - r, x + r, y + r), fill=color)


@lru_cache(maxsize=96)
def face(emotion, mouth, blink, look=0):
    # Supersampled vector art is cached; it is not regenerated by an image model.
    im = Image.new("RGBA", (420, 480))
    d = ImageDraw.Draw(im)

    def ellipse(box, fill, outline=None, width=1):
        d.ellipse(tuple(v * 2 for v in box), fill=fill, outline=outline, width=width * 2)

    def path(points, fill, outline=None, width=1):
        pts = [(x * 2, y * 2) for x, y in points]
        d.polygon(pts, fill=fill)
        if outline:
            d.line(pts + [pts[0]], fill=outline, width=width * 2, joint="curve")

    # White face, subtle volume, individually articulated features.
    ellipse((34, 60, 170, 199), "#d9e5df", INK, 5)
    ellipse((42, 64, 168, 193), "#f7fcf6")
    for ex in (79, 128):
        if blink:
            pts = curve([(ex - 13, 118), (ex - 5, 111), (ex + 7, 111), (ex + 14, 118)])
            d.line([(x * 2, y * 2) for x, y in pts], fill=INK, width=6)
        else:
            ellipse((ex - 15, 101, ex + 16, 140), "#ffffff", INK, 2)
            dy = 3 if emotion == "thinking" else 0
            ellipse((ex - 4 + look, 111 + dy, ex + 9 + look, 129 + dy), INK)
            ellipse((ex - 1 + look, 113 + dy, ex + 3 + look, 118 + dy), "white")
        brow = 88 if emotion == "surprised" else 93
        if emotion == "concerned":
            pts = [(ex - 14, brow + 6), (ex, brow - 2), (ex + 14, brow - 5 if ex < 100 else brow + 8)]
        elif emotion == "thinking" and ex > 100:
            pts = [(ex - 14, brow), (ex, brow - 4), (ex + 14, brow)]
        else:
            pts = curve([(ex - 14, brow + 4), (ex - 7, brow - 4), (ex + 7, brow - 4), (ex + 14, brow + 4)])
        d.line([(x * 2, y * 2) for x, y in pts], fill=INK, width=7, joint="curve")
    if mouth == 2 or emotion == "surprised":
        ellipse((95, 151, 118, 177), INK)
        ellipse((99, 168, 114, 176), "#d68483")
    elif mouth == 1:
        path(
            curve([(81, 151), (98, 160), (119, 160), (136, 148)])
            + curve([(136, 148), (128, 183), (96, 188), (81, 151)])[1:],
            INK,
        )
        path([(87, 155), (129, 154), (125, 161), (92, 163)], "#ffffff")
    elif emotion == "concerned":
        d.arc((88 * 2, 160 * 2, 129 * 2, 179 * 2), 185, 350, fill=INK, width=5)
    else:
        d.arc((81 * 2, 140 * 2, 139 * 2, 173 * 2), 8, 170, fill=INK, width=5)
    # Distinctive beret with brim, highlight and a stem; original drawn asset.
    hat = curve([(15, 92), (5, 67), (66, 22), (137, 22)])
    hat += curve([(137, 22), (190, 17), (189, 62), (155, 68)])[1:]
    hat += curve([(155, 68), (105, 61), (71, 83), (29, 96)])[1:]
    path(hat, "#d94332", INK, 4)
    path(
        curve([(30, 76), (61, 42), (117, 30), (151, 32)])
        + curve([(151, 32), (162, 37), (153, 47), (132, 46)])[1:]
        + curve([(132, 46), (86, 43), (62, 63), (30, 76)])[1:],
        "#f35d43",
    )
    path(
        curve([(24, 87), (69, 69), (118, 55), (160, 60)])
        + curve([(160, 60), (135, 75), (80, 75), (32, 98)])[1:],
        "#a52e28",
        INK,
        2,
    )
    path([(92, 28), (85, 15), (89, 10), (96, 13), (100, 26)], "#bd3a31", INK, 2)
    return im.resize((210, 240), Image.Resampling.LANCZOS)


@lru_cache(maxsize=128)
def glove(kind, angle):
    im = Image.new("RGBA", (80, 100))
    d = ImageDraw.Draw(im)
    d.ellipse((20, 29, 58, 75), fill=INK)
    if kind == "point":
        rounded_line(d, [(40, 42), (42, 8)], 12)
        rounded_line(d, [(24, 48), (14, 62)], 11)
        for x in (34, 45, 55):
            rounded_line(d, [(x, 58), (x, 76)], 10)
    elif kind == "thumb":
        rounded_line(d, [(23, 47), (16, 19)], 13)
        for y in (41, 52, 63):
            rounded_line(d, [(38, y), (61, y)], 12)
    elif kind == "open":
        for x, y in [(23, 16), (35, 9), (47, 12), (59, 24)]:
            rounded_line(d, [(x, 46), (x, y)], 10)
        rounded_line(d, [(23, 53), (9, 38)], 11)
    else:
        for x, y in [(25, 79), (36, 86), (47, 85), (57, 77)]:
            rounded_line(d, [(x, 53), (x, y)], 10)
        rounded_line(d, [(22, 48), (11, 62)], 11)
    im = im.resize((40, 50), Image.Resampling.LANCZOS)
    return im.rotate(angle, resample=Image.Resampling.BICUBIC, expand=False)


GESTURES = {
    "present": ((112, 626), (278, 560), "rest", "open", 0, -90),
    "point": ((112, 626), (290, 504), "rest", "point", 0, -90),
    "think": ((176, 606), (174, 421), "rest", "rest", 0, 30),
    "shrug": ((65, 516), (277, 516), "open", "open", 60, -60),
    "thumbs_up": ((115, 625), (272, 496), "rest", "thumb", 0, 0),
    "wave": ((110, 626), (276, 368), "rest", "open", 0, 0),
}
CAMERAS = {"wide": (1.0, 0.0, 0.0), "medium": (1.12, -4.0, 15.0), "close": (1.55, 105.0, 90.0)}


class PresenterRenderer:
    def __init__(self, script, segments, audio, rate, width=540):
        if not features.check_feature("raqm"):
            raise RuntimeError("Pillow needs RAQM for Arabic")
        self.script, self.segments = script, segments
        self.audio, self.rate = audio, rate
        self.width = width
        self.font_path = str(find_font())
        self.direction = "rtl" if script.language == "ar" else "ltr"
        # Paint the background and all text once, rather than shaping Arabic every frame.
        self.bg = Image.new("RGB", (540, 960), "#d6e7e9")
        d = ImageDraw.Draw(self.bg)
        for y in range(960):
            q = y / 960
            d.line((0, y, 540, y), fill=(round(185 + 34 * q), round(220 + 8 * q), round(239 - 15 * q)))
        for x in range(0, 540, 31):
            d.line((x, 0, x, 960), fill="#c3d9df")
        for y in range(0, 960, 31):
            d.line((0, y, 540, y), fill="#c3d9df")
        for k in range(18):
            x, y = (k * 137 + 19) % 540, (k * 173 + 83) % 960
            d.ellipse((x, y, x + 11, y + 11), outline="#b5cdd4", width=1)
        self.headlines = [self.headline(s.caption, i) for i, s in enumerate(script.scenes)]
        self.panels = [self.panel(s.visual) for s in script.scenes]
        self.subtitles = []
        self.subtitle_ends = []
        for scene in script.scenes:
            words = scene.narration.split()
            groups = [" ".join(words[i : i + 7]) for i in range(0, len(words), 7)]
            self.subtitles.append([self.subtitle(text) for text in groups])
            cumulative = np.cumsum([len(text.split()) for text in groups])
            self.subtitle_ends.append((cumulative / cumulative[-1]).tolist())

    def font(self, size, mono=False):
        return ImageFont.truetype("DejaVuSansMono.ttf" if mono else self.font_path, size)

    def text_block(self, draw, text, xy, width, size=26, color=INK, max_lines=3, direction=None):
        direction = direction or self.direction
        font = self.font(size)
        while size > 12 and (
            len(wrap_text(text, font, width, direction)) > max_lines
            or any(
                font.getlength(line, direction=direction) > width
                for line in wrap_text(text, font, width, direction)
            )
        ):
            size -= 1
            font = self.font(size)
        lines = wrap_text(text, font, width, direction)
        for i, line in enumerate(lines[:max_lines]):
            while font.getlength(line, direction=direction) > width and len(line) > 1:
                line = line[:-2] + "…"
            draw.text(
                (xy[0], xy[1] + i * size * 1.45),
                line,
                font=font,
                fill=color,
                anchor="mt",
                direction=direction,
            )

    def headline(self, text, index):
        im = Image.new("RGBA", (540, 240))
        d = ImageDraw.Draw(im)
        d.text((500, 26), f"{index + 1:02d}", font=self.font(14), fill="#56757f", anchor="rt")
        self.text_block(d, text, (270, 75), 475, 38, max_lines=2)
        d.rounded_rectangle((230, 213, 310, 219), radius=3, fill=RED)
        return im

    def subtitle(self, text):
        im = Image.new("RGBA", (540, 100))
        d = ImageDraw.Draw(im)
        font = self.font(22)
        for i, line in enumerate(wrap_text(text, font, 470, self.direction)[:3]):
            while font.getlength(line, direction=self.direction) > 470 and len(line) > 1:
                line = line[:-2] + "…"
            d.text(
                (270, 8 + i * 30),
                line,
                font=font,
                fill="white",
                anchor="mt",
                direction=self.direction,
                stroke_width=2,
                stroke_fill="#252a2c",
            )
        return im

    def panel(self, visual):
        im = Image.new("RGBA", (245, 355))
        d = ImageDraw.Draw(im)
        if visual.kind == "none":
            return im
        items = visual.items
        if visual.kind == "code":
            count = min(12, len(visual.code.splitlines()))
            panel_height = min(350, max(190, 122 + count * 26))
        elif visual.kind in ("list", "flow"):
            panel_height = min(350, max(130, 40 + len(items) * 78))
        else:
            panel_height = 350
        d.rounded_rectangle(
            (3, 5, 241, panel_height), radius=17, fill="#fafcfaee", outline="#748d96", width=2
        )
        if visual.kind == "code":
            d.rounded_rectangle((13, 22, 231, panel_height - 40), radius=9, fill="#172832")
            lines = visual.code.splitlines()
            longest = max((len(line) for line in lines), default=1)
            size = min(22, max(12, int(200 / max(1, longest) / 0.61)))
            if len(lines) > 8:
                size = min(size, 15)
            font = self.font(size, True)
            limit = max(1, int(198 / font.getlength("M")))
            for i, line in enumerate(lines[:12]):
                if len(line) > limit:
                    line = line[: max(0, limit - 1)] + "…"
                d.text(
                    (23, 49 + i * min(26, max(20, size + 3))),
                    line,
                    font=font,
                    fill="#ffb2a4" if ";" in line else "#e7f0e9",
                    direction="ltr",
                )
            if items:
                self.text_block(d, items[0], (123, panel_height - 32), 218, 16, max_lines=1)
        elif visual.kind == "compare":
            for i, label in enumerate(items[:2]):
                y = 50 + i * 145
                d.rounded_rectangle((17, y, 228, y + 110), radius=12, fill="#e0eee6" if i else "#f6e1dc")
                self.text_block(d, label, (123, y + 22), 190, 23, max_lines=2)
        else:
            for i, label in enumerate(items):
                y = 32 + i * 78
                d.rounded_rectangle((17, y, 228, y + 57), radius=10, fill="#dfeaf0")
                self.text_block(d, label, (123, y + 12), 190, 21, max_lines=2)
                if visual.kind == "flow" and i < len(items) - 1:
                    d.line((123, y + 59, 123, y + 76), fill=RED, width=3)
                    d.polygon([(117, y + 70), (123, y + 77), (129, y + 70)], fill=RED)
        return im.crop((0, 0, 245, panel_height + 5))

    def character(self, t, index, local):
        scene = self.script.scenes[index]
        previous = self.script.scenes[max(index - 1, 0)]
        u = ease(local / 0.35) if index else ease(local / 0.4)
        old = GESTURES[previous.gesture] if index else GESTURES["present"]
        new = GESTURES[scene.gesture]
        im = Image.new("RGBA", (540, 960))
        d = ImageDraw.Draw(im)
        breath = 2 * math.sin(t * 2.4)
        lean = 3 * math.sin(t * 0.9 + index)
        shoulder = (168 + lean, 449 + breath)
        hip = (168, 645)
        # Full silhouette: tapered torso, curved arms, shaped shoes and gloves.
        d.ellipse((94, 848, 254, 876), fill="#485a5b40")
        d.polygon(
            [
                (163 + lean, 421 + breath),
                (175 + lean, 421 + breath),
                (179 + lean, 449 + breath),
                (177, 628),
                (174, 652),
                (162, 652),
                (159, 628),
                (157 + lean, 449 + breath),
            ],
            fill=INK,
        )
        for pts in [[hip, (150, 739), (134, 849)], [hip, (192, 738), (207, 849)]]:
            rounded_line(d, pts, 12)
        d.ellipse((110, 839, 151, 862), fill=INK)
        d.ellipse((195, 843, 246, 865), fill=INK)
        for side in [0, 1]:
            a, b = old[side], new[side]
            wrist = (mix(a[0], b[0], u), mix(a[1], b[1], u) + breath)
            cycle = local % 3.8
            recovery = ease((cycle - 2.1) / 0.5) * (1 - ease((cycle - 3.1) / 0.6)) * 0.65
            rest = GESTURES["present"][side]
            wrist = (mix(wrist[0], rest[0], recovery), mix(wrist[1], rest[1], recovery))
            if scene.gesture == "wave" and side == 1:
                wrist = (wrist[0] + 10 * math.sin(local * 7) * u, wrist[1])
            elif scene.gesture in ("point", "present") and side == 1:
                wrist = (wrist[0] + 3 * math.sin(local * 3.2) * u, wrist[1] + 2 * math.sin(local * 2.1))
            elbow, end = joint(shoulder, wrist, 104, 110, 1 if side else -1)
            rounded_line(d, [shoulder, elbow, end], 10)
            kind = new[2 + side] if u > 0.5 else old[2 + side]
            angle = round(mix(old[4 + side], new[4 + side], u) / 5) * 5
            hand = glove(kind, angle)
            im.alpha_composite(hand, (round(end[0] - 20), round(end[1] - 25)))
        start = max(0, int((t - 0.025) * self.rate))
        end = min(len(self.audio), int((t + 0.025) * self.rate))
        energy = float(np.sqrt(np.mean(self.audio[start:end] ** 2))) if end > start else 0
        mouth = 0 if energy < 0.015 else 1 if energy < 0.09 else 2
        blink = abs((t + 1.2) % 3.9 - 1.95) < 0.07
        head = face(scene.emotion, mouth, blink, 3 if scene.gesture == "point" else 0)
        im.alpha_composite(head, (round(65 + lean), round(225 + breath)))
        prior = CAMERAS[previous.camera] if index else CAMERAS[scene.camera]
        current = CAMERAS[scene.camera]
        zoom, panx, pany = [mix(a, b, u) for a, b in zip(prior, current)]
        zoom += 0.015 * ease(local / max(0.1, self.segments[index]["end"] - self.segments[index]["start"]))
        # Camera applies to the character layer, leaving text readable.
        tx = 168 * (1 - zoom) + panx
        ty = 450 * (1 - zoom) + pany
        crop = (30, 220, 335, 885)
        actor = im.crop(crop)
        actor = actor.resize(
            (round(actor.width * zoom), round(actor.height * zoom)), Image.Resampling.BILINEAR
        )
        return actor, (round(crop[0] * zoom + tx), round(crop[1] * zoom + ty))

    def frame(self, t):
        index = next((i for i, s in enumerate(self.segments) if t < s["end"]), len(self.segments) - 1)
        segment = self.segments[index]
        local = t - segment["start"]
        image = self.bg.copy().convert("RGBA")
        actor, position = self.character(t, index, local)
        image.alpha_composite(actor, position)
        if self.script.scenes[index].camera != "close" and self.script.scenes[index].visual.kind != "none":
            enter = ease(local / 0.4)
            panel = self.panels[index]
            image.alpha_composite(panel, (round(540 - 245 * enter), 450))
        image.alpha_composite(self.headlines[index])
        subtitles = self.subtitles[index]
        # Estimated phrase pacing only; not word-level or phoneme alignment.
        fraction = max(0, min(0.999, local / (segment["end"] - segment["start"])))
        chunk = min(len(subtitles) - 1, bisect_right(self.subtitle_ends[index], fraction))
        image.alpha_composite(subtitles[chunk], (0, 865))
        image = image.convert("RGB")
        if self.width != 540:
            image = image.resize((self.width, round(self.width * 16 / 9 / 2) * 2), Image.Resampling.LANCZOS)
        return image


def validate_audio(script, metadata, audio_path):
    # Reuse the existing strict contiguous timing check with the same spoken text.
    legacy = SimpleNamespace(beats=script.scenes, language=script.language)
    segments = validate_timeline(legacy, metadata)
    info = sf.info(audio_path)
    if not math.isfinite(info.duration) or abs(info.duration - metadata["duration"]) > 0.02:
        raise ValueError("WAV duration differs from narration metadata")
    return segments


def render(script, audio_path, metadata, output, profile="fast"):
    if profile not in PROFILES:
        raise ValueError("Choose fast/quality profile")
    width, fps, preset = PROFILES[profile]
    segments = validate_audio(script, metadata, audio_path)
    audio, rate = sf.read(audio_path, dtype="float32", always_2d=True)
    if not np.isfinite(audio).all():
        raise ValueError("Non-finite audio")
    audio = audio.mean(axis=1)
    started = time.perf_counter()
    rig = PresenterRenderer(script, segments, audio, rate, width)
    count = math.ceil(metadata["duration"] * fps)
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    height = round(width * 16 / 9 / 2) * 2
    with tempfile.TemporaryDirectory(dir=output.parent) as work:
        temp = Path(work) / "video.mp4"
        log = Path(work) / "ffmpeg.log"
        with log.open("wb") as errors:
            process = subprocess.Popen(
                [
                    "ffmpeg",
                    "-y",
                    "-v",
                    "error",
                    "-f",
                    "rawvideo",
                    "-pix_fmt",
                    "rgb24",
                    "-s",
                    f"{width}x{height}",
                    "-r",
                    str(fps),
                    "-i",
                    "-",
                    "-i",
                    str(audio_path),
                    "-map",
                    "0:v:0",
                    "-map",
                    "1:a:0",
                    "-c:v",
                    "libx264",
                    "-preset",
                    preset,
                    "-crf",
                    "22",
                    "-pix_fmt",
                    "yuv420p",
                    "-threads",
                    "2",
                    "-c:a",
                    "aac",
                    "-b:a",
                    "128k",
                    "-t",
                    str(metadata["duration"]),
                    "-movflags",
                    "+faststart",
                    str(temp),
                ],
                stdin=subprocess.PIPE,
                stderr=errors,
            )
            try:
                for frame in range(count):
                    process.stdin.write(rig.frame(frame / fps).tobytes())
                process.stdin.close()
                if process.wait():
                    raise RuntimeError(log.read_text()[-1500:])
                temp.replace(output)
            except BaseException:
                process.kill()
                process.wait()
                raise
    return {
        "wall_seconds": time.perf_counter() - started,
        "fps": fps,
        "width": width,
        "height": height,
        "frames": count,
    }
